"""Async Postgres writer for generated lessons.

Used by the workflow's deterministic write step. Reads are handled separately by
``tools.answers_toolkit.AnswersToolkit``.
"""

import uuid

import psycopg

from utils.db_config import get_connection_string

_INSERT_LESSON = """
    INSERT INTO lessons (user_id, lesson_uuid, lesson_script, duration)
    VALUES (%s, %s, %s, %s)
"""


class PostgresDB:
    """Writes generated lesson plans to the ``lessons`` table (async)."""

    def __init__(self, connection_string: str | None = None):
        self.connection_string = connection_string or get_connection_string()

    async def insert_lesson(
        self,
        user_id: str,
        lesson_uuid: uuid.UUID,
        lesson_script: str,
        duration: int,
    ) -> uuid.UUID:
        """Insert one generated lesson and return its ``lesson_uuid``.

        Args:
            user_id: The user's email address.
            lesson_uuid: UUID generated by the caller (the deterministic step).
            lesson_script: The generated lesson plan text.
            duration: Lesson duration in minutes.

        Returns:
            The ``lesson_uuid`` of the inserted row.

        Note:
            ``created_at`` and ``updated_at`` are left to the DB ``DEFAULT now()``.
        """
        async with await psycopg.AsyncConnection.connect(
            self.connection_string
        ) as conn:
            async with conn.cursor() as cur:
                await cur.execute(
                    _INSERT_LESSON,
                    (user_id, lesson_uuid, lesson_script, duration),
                )
            await conn.commit()
        return lesson_uuid
